class SourceFetchError(Exception):
    def __init__(self, response: ClientResponse):
        self.status = response.status
        super().__init__(f"Source({response.url}) content is not available: {self.status}")


class KhlReader:
    PLAYER_POSITIONS = {"в": "goalie", "з": "defenseman", "н": "forward"}
    CAPTAIN_MAP = {"а": "A", "к": "C"}

    def __init__(self):
        self.source_page_url: str = None
        self._session: ClientSession = None
        self.api_payload: str = ''
        self.khl_sessid = None
        self.errors = []
        self.request_timeout = aiohttp.ClientTimeout(total=BASE_TIMEOUT)
        self.HEADERS = {'User-Agent': random.choice(USER_AGENTS)}
        self.API_HEADERS = {**self.HEADERS, 'Content-Type': 'application/x-www-form-urlencoded; charset=UTF-8'}

    async def __aenter__(self):
        try:
            async with aiohttp.ClientSession(headers=self.HEADERS, timeout=self.request_timeout) as self._session:
                await self._fetch_page_html()
                await self._run_ops()
        finally:
            self._session = None
        return self

    async def __aexit__(self, exc_type, exc_val, exc_tb):
        return

    async def _fetch_page_html(self) -> None:
        if not self.source_page_url:
            self._raise(Exception(f"Адрес базовой страницы КХЛ не указан"), False)
        async with self._session.get(self.source_page_url) as response:
            if response.status != 200:
                self._raise(SourceFetchError(response), False)
            else:
                try:
                    content = await response.text()
                    if re_obj := re.search(r'"bitrix_sessid":"([a-z0-9]+)"', content):
                        self.khl_sessid = re_obj.group(1)
                except Exception as e:
                    self._raise(e, False)
        if not self.khl_sessid:
            self._raise(Exception('Значение bitrix_sessid не найдено на странице'), False)

    async def _fetch_api_data(self, api_url: str, attr: str):
        async with self._session.post(api_url, headers=self.API_HEADERS, data=self.api_payload) as response:
            if response.status == 200:
                try:
                    api_data = await response.json()
                    if api_data.get('status') != 'success':
                        errors = api_data.get('errors') or ['Неизвестная ошибка']
                        for e in errors:
                            self._raise(Exception(f'Ошибка получения данных API КХЛ[{api_url}]: {str(e)}'))
                    else:
                        setattr(self, attr, api_data.get('data', {}))
                except Exception as e:
                    self._raise(e)
            else:
                self._raise(SourceFetchError(response), False)

